// Preserve a returned bitmap byte-for-byte. No image transformation is performed here.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const [id, source, attemptText] = process.argv.slice(2);
const root = path.resolve(__dirname, '../..');
const people = require('./people-cases.cjs');
assert.ok(['coffee', 'astronaut', 'rocket', 'chelsea', ...Object.keys(people.cases)].includes(id));
const run = people.cases[id] ? people.run : '20260910-real-scenes-01';
const attempt = Number(attemptText);
assert.ok([1, 2].includes(attempt));
const file = path.join(root, 'runs', run, id + '.json');
const r = JSON.parse(fs.readFileSync(file, 'utf8'));
const bytes = fs.readFileSync(source);
assert.equal(bytes.subarray(0, 8).toString('hex'), '89504e470d0a1a0a');
const actualSize = [bytes.readUInt32BE(16), bytes.readUInt32BE(20)];
const hash = b => crypto.createHash('sha256').update(b).digest('hex');
const name = 'source-' + r.order + '-' + id + '-' + r.mode + '-' + r.ratio.replace(':', 'x') + '-' + actualSize.join('x') + '-attempt-' + attempt + '.png';
const output = 'assets/generated/' + r.run + '/' + name;
assert.ok(!fs.existsSync(path.join(root, output)), '不得覆盖已保存的生成结果');
fs.copyFileSync(source, path.join(root, output));
const prompt = 'runs/' + r.run + '/prompts/' + id + (attempt === 2 ? '-retry' : '') + '.txt';
const record = { attempt, recordedAt: new Date().toISOString(), output, actualSize, outputSha256: hash(bytes), prompt, promptSha256: hash(fs.readFileSync(path.join(root, prompt))), tool: 'built-in imagegen', originalToolFilename: path.basename(source), postprocessing: 'none', visualReview: null };
r.attemptRecords = [...(r.attemptRecords || []), record];
r.attempts = r.attemptRecords.length;
r.state = 'generated-awaiting-review';
fs.writeFileSync(file, JSON.stringify(r, null, 2) + '\n');
console.log(JSON.stringify({ id, attempt, output, actualSize }));
